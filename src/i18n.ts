const lang = (typeof navigator !== "undefined" && navigator.language) || "en";
const isRu = lang.toLowerCase().startsWith("ru");

export const t: Dict = isRu ? ru : en;

export function errText(code: string, message: string): string {
  if (isRu && ruErrors[code]) return message ? `${ruErrors[code]} (${message})` : ruErrors[code];
  return message || code;
}
